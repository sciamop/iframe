int keymap_mac_code(int usage) {
    for (size_t i = 0; i < sizeof table / sizeof *table; i++)
        if (table[i].usage == usage) return table[i].mac;
    return -1;
}

uint32_t keymap_modifier(int mac) {
    switch (mac) {
    case 0x38: case 0x3C: return MOD_SHIFT;
    case 0x3B: case 0x3E: return MOD_CONTROL;
    case 0x3A: case 0x3D: return MOD_OPTION;
    case 0x37: case 0x36: return MOD_COMMAND;
    default: return 0;
    }
}
